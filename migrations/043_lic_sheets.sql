-- LIC Premium Due + Commission sheets (043, after 042). Adds only; the server running before this
-- keeps working. Plan: docs/plans/2026-11-28-lic-premium-due.md
--
-- Server-only tables: RLS is on with no policies, so the browser (anon / authenticated roles)
-- can neither read nor write them. Every server query filters on agent_id.
BEGIN;

CREATE TABLE IF NOT EXISTS lic_uploads (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  agent_id uuid NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('due', 'commission')),
  period text NOT NULL CHECK (period ~ '^\d{4}-\d{2}$'),
  batch smallint,
  lic_agent_code text NOT NULL DEFAULT '',
  branch_code text,
  file_sha256 text NOT NULL,
  row_count integer NOT NULL,
  totals jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (agent_id, file_sha256)
);
CREATE INDEX IF NOT EXISTS lic_uploads_agent_idx ON lic_uploads (agent_id, kind, period DESC, created_at DESC);

CREATE TABLE IF NOT EXISTS lic_due_rows (
  upload_id bigint NOT NULL REFERENCES lic_uploads(id) ON DELETE CASCADE,
  agent_id uuid NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
  sno integer NOT NULL,
  policy_no text NOT NULL,
  holder_name text NOT NULL,
  doc date NOT NULL,
  plan_no integer NOT NULL,
  lic_term integer NOT NULL,
  mode text NOT NULL CHECK (mode IN ('Y', 'H', 'Q', 'M', 'S')),
  fup text NOT NULL CHECK (fup ~ '^\d{4}-\d{2}$'),
  flag text,
  inst_prem numeric(14, 2) NOT NULL,
  due_count integer NOT NULL,
  gst numeric(14, 2) NOT NULL DEFAULT 0,
  total_prem numeric(14, 2) NOT NULL,
  est_comm numeric(14, 2) NOT NULL,
  PRIMARY KEY (upload_id, sno)
);
CREATE INDEX IF NOT EXISTS lic_due_rows_agent_idx ON lic_due_rows (agent_id, policy_no);

CREATE TABLE IF NOT EXISTS lic_paid_rows (
  upload_id bigint NOT NULL REFERENCES lic_uploads(id) ON DELETE CASCADE,
  agent_id uuid NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
  sno integer NOT NULL,
  holder_name text NOT NULL,
  policy_no text NOT NULL,
  plan_no integer NOT NULL,
  term integer NOT NULL,
  due_date date NOT NULL,
  risk_date date NOT NULL,
  cbo text NOT NULL DEFAULT '',
  adj_date date NOT NULL,
  premium numeric(14, 2) NOT NULL,
  commission numeric(14, 2) NOT NULL,
  PRIMARY KEY (upload_id, sno)
);
CREATE INDEX IF NOT EXISTS lic_paid_rows_agent_idx ON lic_paid_rows (agent_id, policy_no, due_date);

ALTER TABLE lic_uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE lic_due_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE lic_paid_rows ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON lic_uploads, lic_due_rows, lic_paid_rows FROM anon, authenticated;

COMMIT;
