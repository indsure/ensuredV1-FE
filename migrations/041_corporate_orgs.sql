-- IndSure Commercial (/corporate): organisations, employee logins, invites and a sign-in history.
-- Additive. The backend running before this keeps working: everything saved so far becomes organisation 1,
-- and row 1 of corp_book is still row 1. RLS on with no policies, so browsers cannot reach these tables.
BEGIN;

CREATE TABLE IF NOT EXISTS corp_orgs (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  owner_name text NOT NULL DEFAULT 'Owner',
  owner_email text,
  owner_hash text,
  active boolean NOT NULL DEFAULT true,
  failed integer NOT NULL DEFAULT 0,
  locked_until timestamptz,
  last_login timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO corp_orgs (id, code, name) VALUES (1, 'IC10001', 'Organisation 1') ON CONFLICT (id) DO NOTHING;
SELECT setval(pg_get_serial_sequence('corp_orgs', 'id'), GREATEST((SELECT max(id) FROM corp_orgs), 1));

CREATE TABLE IF NOT EXISTS corp_members (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  org_id integer NOT NULL REFERENCES corp_orgs(id),
  user_code text NOT NULL UNIQUE,
  email text NOT NULL,
  name text NOT NULL,
  designation text NOT NULL DEFAULT '',
  departments jsonb NOT NULL DEFAULT '[]'::jsonb,
  role text NOT NULL CHECK (role IN ('ops', 'accounts', 'admin', 'readonly')),
  pin_hash text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  failed integer NOT NULL DEFAULT 0,
  locked_until timestamptz,
  last_login timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, email)
);

-- One link per row: an owner setting a password, an employee joining, or an employee setting a new PIN.
-- Only a hash of the link's token is kept.
CREATE TABLE IF NOT EXISTS corp_invites (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  org_id integer NOT NULL REFERENCES corp_orgs(id),
  kind text NOT NULL CHECK (kind IN ('owner', 'join', 'pin')),
  email text NOT NULL,
  role text CHECK (role IN ('ops', 'accounts', 'admin', 'readonly')),
  member_id bigint REFERENCES corp_members(id),
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS corp_invites_org_idx ON corp_invites (org_id, created_at DESC);

-- Who signed in, was invited, joined or was switched off. Kept from the start so later logs have a history.
CREATE TABLE IF NOT EXISTS corp_auth_events (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  org_id integer NOT NULL REFERENCES corp_orgs(id),
  member_id bigint REFERENCES corp_members(id),
  who text NOT NULL,
  event text NOT NULL,
  detail text NOT NULL DEFAULT '',
  at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS corp_auth_events_org_idx ON corp_auth_events (org_id, at DESC);

-- One book per organisation: the row's id is the organisation's id.
ALTER TABLE corp_book DROP CONSTRAINT IF EXISTS corp_book_id_check;
ALTER TABLE corp_book_versions ADD COLUMN IF NOT EXISTS org_id integer NOT NULL DEFAULT 1;
ALTER TABLE corp_book_versions DROP CONSTRAINT IF EXISTS corp_book_versions_pkey;
ALTER TABLE corp_book_versions ADD CONSTRAINT corp_book_versions_pkey PRIMARY KEY (org_id, version);
ALTER TABLE corp_feedback ADD COLUMN IF NOT EXISTS org_id integer NOT NULL DEFAULT 1;

ALTER TABLE corp_orgs ENABLE ROW LEVEL SECURITY;
ALTER TABLE corp_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE corp_invites ENABLE ROW LEVEL SECURITY;
ALTER TABLE corp_auth_events ENABLE ROW LEVEL SECURITY;

COMMIT;
