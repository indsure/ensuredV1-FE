-- IndSure Commercial: roles an owner can edit, and teams of people (042, after 041). Adds only; the server
-- running before this keeps working.
BEGIN;

-- A row for a built-in role (ops, accounts, readonly) replaces its default; any other key is the owner's own role.
-- Admin has no row: it always has everything.
CREATE TABLE IF NOT EXISTS corp_roles (
  org_id integer NOT NULL REFERENCES corp_orgs(id),
  key text NOT NULL,
  name text NOT NULL,
  pages jsonb NOT NULL DEFAULT '[]'::jsonb,
  actions jsonb NOT NULL DEFAULT '[]'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, key)
);
CREATE UNIQUE INDEX IF NOT EXISTS corp_roles_name_idx ON corp_roles (org_id, lower(name));

CREATE TABLE IF NOT EXISTS corp_teams (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  org_id integer NOT NULL REFERENCES corp_orgs(id),
  name text NOT NULL,
  lead_id bigint REFERENCES corp_members(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS corp_teams_name_idx ON corp_teams (org_id, lower(name));

CREATE TABLE IF NOT EXISTS corp_team_members (
  team_id bigint NOT NULL REFERENCES corp_teams(id) ON DELETE CASCADE,
  member_id bigint NOT NULL REFERENCES corp_members(id),
  PRIMARY KEY (team_id, member_id)
);

-- The person's CSC or RM code in the records, so a team can filter its customers.
ALTER TABLE corp_members ADD COLUMN IF NOT EXISTS staff_code text NOT NULL DEFAULT '';
ALTER TABLE corp_invites ADD COLUMN IF NOT EXISTS teams jsonb NOT NULL DEFAULT '[]'::jsonb;

-- Roles are no longer only the four built-in ones. The server checks them.
ALTER TABLE corp_members DROP CONSTRAINT IF EXISTS corp_members_role_check;
ALTER TABLE corp_invites DROP CONSTRAINT IF EXISTS corp_invites_role_check;

ALTER TABLE corp_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE corp_teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE corp_team_members ENABLE ROW LEVEL SECURITY;

COMMIT;
