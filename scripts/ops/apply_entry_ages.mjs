// Writes backend/catalog_entry_ages.json into the catalogue.
//
//   node scripts/ops/apply_entry_ages.mjs            patch seeds, print SQL
//   node scripts/ops/apply_entry_ages.mjs --check    report only, change nothing
//
// Each plan's ages go into its seed file as profile.entry_age, so the next
// load_catalog.mjs run keeps them (the loader stores the whole seed as the
// profile). The live catalogue gets the same values from the SQL this prints,
// one UPDATE per plan, which is written to migrations/035_catalog_entry_ages.sql.
// No database connection here: the SQL is for a person to read and run.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SEED_DIR = path.join(REPO_ROOT, 'backend', 'catalog_seed');
const TABLE = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'backend', 'catalog_entry_ages.json'), 'utf-8'));
const OUT_SQL = path.join(REPO_ROOT, 'migrations', '035_catalog_entry_ages.sql');
const check = process.argv.includes('--check');

const seeds = fs.readdirSync(SEED_DIR).filter((f) => f.endsWith('.json')).map((f) => {
  const file = path.join(SEED_DIR, f);
  const raw = fs.readFileSync(file, 'utf-8');
  return { file, raw, seed: JSON.parse(raw) };
});

const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
let patched = 0;
const missing = [];

for (const row of TABLE.plans) {
  const entry = {
    adult_min: row.adult_min, adult_max: row.adult_max, segment: row.segment,
    source: row.source, ref: row.ref, quote: row.quote,
    ...(row.note ? { note: row.note } : {}),
    checked: TABLE.checked,
  };
  const matches = seeds.filter((s) =>
    s.seed.uin === row.uin && (row.variant === undefined || (s.seed.variant ?? '').trim() === row.variant));
  if (matches.length === 0) missing.push(row.uin + (row.variant ? `:${row.variant}` : ''));
  for (const s of matches) {
    s.seed.entry_age = entry;
    if (!check) {
      const indent = (s.raw.match(/\n( +)"/) || [, '  '])[1].length;
      fs.writeFileSync(s.file, JSON.stringify(s.seed, null, indent) + (s.raw.endsWith('\n') ? '\n' : ''));
    }
    patched++;
  }
  const where = row.variant === undefined
    ? `uin = ${sqlStr(row.uin)}`
    : `uin = ${sqlStr(row.uin)} AND variant = ${sqlStr(row.variant)}`;
  lines.push(`UPDATE public.policy_catalog SET profile = jsonb_set(profile, '{entry_age}', ${sqlStr(JSON.stringify(entry))}::jsonb), updated_at = now() WHERE ${where};`);
}

const sql = `-- 035: adult entry ages for catalogue health plans (data only, no schema change).
--
-- Generated by scripts/ops/apply_entry_ages.mjs from backend/catalog_entry_ages.json, which
-- records where every value came from. The same values are in backend/catalog_seed/*.json, so
-- a catalogue reload keeps them. The plan ranking (services/planRecommend.ts) leaves out a plan
-- whose known entry age excludes the client, and youth or senior plans whose ages are unknown.
--
-- Safe to run more than once. Undo: 035_catalog_entry_ages_down.sql.

BEGIN;
${lines.join('\n')}
COMMIT;

-- Check:
--   SELECT count(*) FROM public.policy_catalog WHERE profile ? 'entry_age';
`;

if (!check) {
  fs.writeFileSync(OUT_SQL, sql);
  fs.writeFileSync(OUT_SQL.replace('.sql', '_down.sql'),
    "-- Undo 035: remove the entry ages from the live catalogue. The seed files keep them.\n" +
    "UPDATE public.policy_catalog SET profile = profile - 'entry_age' WHERE profile ? 'entry_age';\n");
}
console.log(`${TABLE.plans.length} plans in the table, ${patched} seed files ${check ? 'would be ' : ''}patched.`);
if (missing.length) console.log(`No seed file for: ${missing.join(', ')}`);
if (!check) console.log(`SQL written to ${path.relative(REPO_ROOT, OUT_SQL)}`);
